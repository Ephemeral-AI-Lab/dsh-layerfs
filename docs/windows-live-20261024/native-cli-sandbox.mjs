import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const repo = 'C:/Users/yifan/code/Ephemeral-AI-Lab/dsh-layerfs';
const require = createRequire('C:/Users/yifan/code/Ephemeral-AI-Lab/deepseek-harness/packages/shell/pwsh-sandbox/package.json');
const mod = name => import(pathToFileURL(require.resolve(name)).href);
const { Context } = await mod('@deepseek-ai/cordis');
const { LocalSandboxProvider } = await mod('@deepseek-ai/dsh-sandbox-local');
const { SandboxPolicyService } = await mod('@deepseek-ai/dsh-sandbox-policy');
const { SessionProjectionRegistry } = await mod('@deepseek-ai/dsh-session-projection');
const { default: LocalSubprocessRuntime } = await mod('@deepseek-ai/dsh-subprocess-local');
const executorPackage = 'C:/Users/yifan/code/Ephemeral-AI-Lab/deepseek-harness/packages/shell/pwsh-sandbox/';
const { SandboxPwshExecutor } = await import(pathToFileURL(executorPackage + JSON.parse(readFileSync(executorPackage+'package.json','utf8')).main));
const { shimOnPath } = await import(pathToFileURL(repo+'/packages/host/src/cli-path.js'));
const { resolveConfig } = await import(pathToFileURL(repo+'/packages/host/src/config.js'));
const { deploymentEnv } = await import(pathToFileURL(repo+'/packages/host/src/layerfs-client.js'));
const profile = 'C:/Users/yifan/.dsh/profiles/web';
const workspace = profile+'/dsh-layerfs-mock/Scenarios';
const project = JSON.parse(readFileSync(profile+'/dsh-layerfs/bindings.json','utf8')).projects['mock-tour'];
const spec = resolveConfig({wslHome:'/var/lib/dsh-layerfs-windows/default'}, {dir:profile});
const dshEnv = Object.fromEntries(Object.entries(deploymentEnv(spec, project)).map(([k,v])=>['DSH_LAYERFS_'+k,v]));
Object.assign(dshEnv, {DSH_LAYERFS_PROJECT: project.name, DSH_LAYERFS_CLI: spec.cli});
const off = shimOnPath();
const ctx = new Context();
try {
  await ctx.plugin(SessionProjectionRegistry);
  await ctx.plugin(LocalSandboxProvider, {});
  await ctx.plugin(SandboxPolicyService, {mode:'workspace-write',workspaceRoot:workspace});
  await ctx.plugin(LocalSubprocessRuntime);
  await ctx.plugin(SandboxPwshExecutor, {});
  const shell = ctx.get('shell');
  const execution = await shell.execute(shell.resolve({ command:'layerfs project list_branches; exit $LASTEXITCODE', workdir:workspace, timeoutMs:20000, dshEnv }));
  const result = await execution.result();
  console.log(JSON.stringify(result));
  assert.equal(result.exitCode,0);
  assert.equal(result.sandbox.mode,'workspace-write');
  assert.match(result.stdout.text,/main/);
  console.log('PASS: layerfs command read the existing project through the real Windows sandbox and WSL worker');
} finally { off(); }
