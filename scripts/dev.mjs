#!/usr/bin/env node
// Run DeepSeek Harness from this repository's devDependency with a private
// DSH_HOME and a --patch overlay that loads this checkout. Nothing outside
// .dev/ is written: no user profile, no ~/.layerfs.
//
//   node scripts/dev.mjs [--port 3091] [--fresh] [-- extra dsh args]
//
// Env: DSH_LAYERFS_CLI / DSH_LAYERFS_DAEMON / DSH_LAYERFS_BUNDLE pin LayerFS; unset,
// the newest runtime installed in ~/.layerfs is used (scripts/runtime-pin.mjs). DSH_LAYERFS_CACHE_HOME
// names the prepared machine image cache; unset, the CLI uses the per-user cache
// (~/.cache), which also holds the default Linux bundle.
import { spawn, spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { runtimePin } from './runtime-pin.mjs'

const root = new URL('..', import.meta.url).pathname.replace(/\/$/, '')
const args = process.argv.slice(2)
const flag = (name, fallback) => {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : fallback
}
const port = flag('--port', process.env.DSH_LAYERFS_DEV_PORT ?? '3091')
const dev = process.env.DSH_LAYERFS_DEV_DIR ?? join(root, '.dev')
if (args.includes('--fresh')) rmSync(dev, { recursive: true, force: true })
mkdirSync(join(dev, 'state'), { recursive: true })

const env = { ...process.env, DSH_HOME: join(dev, 'state') }
const pin = runtimePin(env)
if (!pin) { console.error('dev.mjs: no LayerFS CLI. Set DSH_LAYERFS_CLI (and _DAEMON, _BUNDLE) or install a runtime from the app.'); process.exit(1) }
env.DSH_LAYERFS_CLI = pin.cli
if (pin.daemon) env.DSH_LAYERFS_DAEMON = pin.daemon
if (pin.bundle) env.DSH_LAYERFS_BUNDLE = pin.bundle
console.log(`dev.mjs: LayerFS CLI ${pin.cli}`)
env.DSH_LAYERFS_HOME ??= join(dev, 'layerfs-home')
env.DSH_LAYERFS_SESSION_HOME ??= join(dev, 'project-sessions')

const bin = join(root, 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js')

// Install this checkout into the private profile the way a user would (link:).
const profile = join(dev, 'state', 'profiles', 'web', 'package.json')
if (!existsSync(profile) || !readFileSync(profile, 'utf8').includes('"dsh-layerfs"')) {
  const r = spawnSync(process.execPath, [bin, 'plugin', '--profile', 'web', 'add', `link:${root}`], { env, stdio: 'inherit' })
  if (r.status !== 0) process.exit(r.status ?? 1)
}

const overlay = join(dev, 'overlay.yml')
const extra = process.env.DSH_LAYERFS_DEV_OVERLAY ? readFileSync(process.env.DSH_LAYERFS_DEV_OVERLAY, 'utf8') : '[]\n'
writeFileSync(overlay, `# generated by scripts/dev.mjs\n${extra}`)

const rest = args.includes('--') ? args.slice(args.indexOf('--') + 1) : []
const child = spawn(process.execPath, [bin, '--profile', 'web', '--patch', overlay, '--host', '127.0.0.1', '--port', port, '--no-open', ...rest], { env, stdio: ['inherit', 'pipe', 'inherit'] })
// Forward output; record the authenticated launch URL for tools/ (url.txt).
child.stdout.on('data', (chunk) => {
  process.stdout.write(chunk)
  const url = String(chunk).match(/https?:\/\/\S+\?token=\S+/)?.[0]
  if (url) writeFileSync(join(dev, 'url.txt'), `${url}\n`)
})
for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => child.kill(sig))
child.on('exit', (code) => process.exit(code ?? 0))
